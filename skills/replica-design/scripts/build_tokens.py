#!/usr/bin/env python3
"""Compile tokens.json into tokens.css and Tailwind theme configuration. Standard library only.

Reads replica/design/tokens.json, validates WCAG contrast, and automatically outputs:
1. tokens.css: CSS custom properties (:root variables)
2. tailwind.tokens.js: Tailwind CSS theme extension

Usage:
    python3 build_tokens.py replica/design/tokens.json
    python3 build_tokens.py --out-css styles/tokens.css --out-tailwind tailwind.tokens.js
"""

import argparse
import importlib.util
import json
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))


def load_contrast_module():
    contrast_path = os.path.join(SCRIPT_DIR, "contrast.py")
    if not os.path.isfile(contrast_path):
        contrast_path = os.path.join(SCRIPT_DIR, "..", "contrast.py")
    if not os.path.isfile(contrast_path):
        return None
    spec = importlib.util.spec_from_file_location("contrast", contrast_path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def generate_css(data):
    lines = [":root {", "  /* Colors */"]
    colors = data.get("color", {})
    for name, val in colors.items():
        if isinstance(val, dict):
            val = val.get("value", "")
        if isinstance(val, str):
            lines.append(f"  --color-{name}: {val};")

    fonts = data.get("font", {})
    if fonts:
        lines.append("")
        lines.append("  /* Typography: Fonts */")
        for name, val in fonts.items():
            lines.append(f"  --font-{name}: {val};")

    types = data.get("type", {})
    if types:
        lines.append("")
        lines.append("  /* Typography: Scales */")
        for name, spec in types.items():
            if isinstance(spec, dict):
                size = spec.get("size")
                line = spec.get("line")
                weight = spec.get("weight")
                if size:
                    lines.append(f"  --text-{name}-size: {size}px;")
                if line:
                    lines.append(f"  --text-{name}-line: {line}px;")
                if weight:
                    lines.append(f"  --text-{name}-weight: {weight};")

    space = data.get("space", [])
    if space and isinstance(space, list):
        lines.append("")
        lines.append("  /* Spacing */")
        for i, val in enumerate(space):
            lines.append(f"  --space-{i}: {val}px;")

    radius = data.get("radius", {})
    if radius:
        lines.append("")
        lines.append("  /* Radius */")
        for name, val in radius.items():
            unit = "px" if isinstance(val, (int, float)) else ""
            lines.append(f"  --radius-{name}: {val}{unit};")

    shadow = data.get("shadow", {})
    if shadow:
        lines.append("")
        lines.append("  /* Shadows */")
        for name, val in shadow.items():
            lines.append(f"  --shadow-{name}: {val};")

    motion = data.get("motion", {})
    if motion:
        lines.append("")
        lines.append("  /* Motion */")
        for name, val in motion.items():
            lines.append(f"  --motion-{name}: {val};")

    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def generate_tailwind(data):
    colors = {}
    for name in data.get("color", {}):
        colors[name] = f"var(--color-{name})"

    font_family = {}
    for name, val in data.get("font", {}).items():
        if isinstance(val, str):
            parts = [p.strip().strip("'\"") for p in val.split(",")]
            font_family[name] = parts

    font_size = {}
    for name, spec in data.get("type", {}).items():
        if isinstance(spec, dict) and "size" in spec:
            size_rem = f"{spec['size'] / 16.0:.4f}".rstrip("0").rstrip(".") + "rem"
            opts = {}
            if "line" in spec:
                opts["lineHeight"] = f"{spec['line'] / 16.0:.4f}rem".rstrip("0").rstrip(".") + "rem"
            if "weight" in spec:
                opts["fontWeight"] = str(spec["weight"])
            font_size[name] = [opts.get("fontSize", f"{spec['size']}px"), opts]

    spacing = {}
    for i, val in enumerate(data.get("space", [])):
        spacing[str(i)] = f"{val}px"

    border_radius = {}
    for name, val in data.get("radius", {}).items():
        border_radius[name] = f"{val}px" if isinstance(val, (int, float)) else str(val)

    box_shadow = data.get("shadow", {})

    theme_extend = {
        "colors": colors,
        "borderRadius": border_radius,
        "boxShadow": box_shadow,
    }
    if font_family:
        theme_extend["fontFamily"] = font_family
    if spacing:
        theme_extend["spacing"] = spacing

    js = [
        "// Generated by build_tokens.py. Do not edit manually.",
        "module.exports = {",
        "  theme: {",
        "    extend: " + json.dumps(theme_extend, indent=6),
        "  }",
        "};",
        "",
    ]
    return "\n".join(js)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("tokens", nargs="?", default="replica/design/tokens.json",
                        help="path to tokens.json (default: replica/design/tokens.json)")
    parser.add_argument("--out-css", help="path for tokens.css (default: same directory as tokens)")
    parser.add_argument("--out-tailwind", help="path for tailwind.tokens.js (default: same directory as tokens)")
    parser.add_argument("--skip-contrast", action="store_true", help="skip WCAG contrast validation")
    args = parser.parse_args(argv)

    if not os.path.isfile(args.tokens):
        print(f"build_tokens: token file '{args.tokens}' not found", file=sys.stderr)
        return 2

    with open(args.tokens, "r", encoding="utf-8") as f:
        data = json.load(f)

    # Validate contrast if module available and not skipped
    if not args.skip_contrast:
        contrast_mod = load_contrast_module()
        if contrast_mod:
            cols = contrast_mod.colours(data)
            pairs = data.get("pairs") or contrast_mod.default_pairs(cols)
            rows = contrast_mod.check(cols, pairs)
            fails = [r for r in rows if not r["aa"]]
            if fails:
                print(f"build_tokens: {len(fails)} token pairs failed WCAG AA contrast check:", file=sys.stderr)
                for f in fails:
                    print(f"  {f['fg']} on {f['bg']}: ratio {f['ratio']:.2f} (needed {f['need']})", file=sys.stderr)
                return 1
            else:
                print(f"Contrast check passed ({len(rows)} pairs tested).")

    token_dir = os.path.dirname(os.path.abspath(args.tokens))
    out_css = args.out_css or os.path.join(token_dir, "tokens.css")
    out_tailwind = args.out_tailwind or os.path.join(token_dir, "tailwind.tokens.js")

    os.makedirs(os.path.dirname(os.path.abspath(out_css)), exist_ok=True)
    os.makedirs(os.path.dirname(os.path.abspath(out_tailwind)), exist_ok=True)

    css_content = generate_css(data)
    with open(out_css, "w", encoding="utf-8") as f:
        f.write(css_content)
    print(f"Wrote CSS variables to {out_css}")

    tw_content = generate_tailwind(data)
    with open(out_tailwind, "w", encoding="utf-8") as f:
        f.write(tw_content)
    print(f"Wrote Tailwind theme extension to {out_tailwind}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
